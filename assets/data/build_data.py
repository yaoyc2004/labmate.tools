#!/usr/bin/env python3
"""
labmate.tools · microscopy hardware library — rebuild microscopy-data.js from microscopy-data.json.

Edit microscopy-data.json (add an objective, camera or scan system, fix a value), then run:

    python build_data.py

Pages load microscopy-data.js as a plain <script> (window.LMT_MICRO), so they also work
when opened straight from disk. Used by 8.2 Nyquist Calculator and 8.1 Scale Bar Maker.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def check(d):
    errs = []
    for kind in ("objectives", "cameras", "scanSystems", "fluors"):
        ids = [x["id"] for x in d[kind]]
        dup = sorted({x for x in ids if ids.count(x) > 1})
        if dup:
            errs.append(kind + ": duplicate ids " + ", ".join(dup))
    for o in d["objectives"]:
        n = d["_meta"]["media"].get(o["immersion"])
        if n is None:
            errs.append(o["id"] + ": unknown immersion " + o["immersion"])
        elif not (0 < o["na"] < n):
            errs.append(o["id"] + ": NA must be below the immersion index")
        if not (0 < o["mag"] <= 250):
            errs.append(o["id"] + ": magnification")
        if not o.get("source"):
            errs.append(o["id"] + ": no source")
    for c in d["cameras"]:
        if not (1 <= c["pixel_um"] <= 30) or len(c["px"]) != 2:
            errs.append(c["id"] + ": pixel size or pixel count")
        if not c.get("source"):
            errs.append(c["id"] + ": no source")
    for s in d["scanSystems"]:
        if s["type"] == "point" and not (5 <= s["field_mm"] <= 30):
            errs.append(s["id"] + ": field")
        if s["type"] == "disk" and not s.get("pinhole_um"):
            errs.append(s["id"] + ": pinhole")
    for f in d["fluors"]:
        if not (250 < f["exMax"] < f["emMax"] < 1000):
            errs.append(f["id"] + ": peaks")
    return errs


def main():
    d = json.loads((HERE / "microscopy-data.json").read_text(encoding="utf-8"))
    errs = check(d)
    if errs:
        raise SystemExit("\n".join(errs))
    m = d["_meta"]
    out = {
        "schemaVersion": d.get("schemaVersion", 1),
        "compiled": m["compiled"],
        "license": m["license"],
        "media": m["media"],
        "stands": d["stands"],
        "objectives": d["objectives"],
        "cameras": d["cameras"],
        "scanSystems": d["scanSystems"],
        "fluors": d["fluors"],
    }
    js = ("/* labmate.tools · microscopy hardware library (generated by build_data.py from "
          "microscopy-data.json — edit that file, not this one). Data: CC BY 4.0, labmate.tools. */\n"
          "window.LMT_MICRO = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n")
    (HERE / "microscopy-data.js").write_text(js, encoding="utf-8")
    print(f"Wrote microscopy-data.js: {len(d['objectives'])} objectives, {len(d['cameras'])} cameras, "
          f"{len(d['scanSystems'])} scan systems, {len(d['fluors'])} dyes")
    write_table(d)


def esc(s):
    return str(s).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


def links(src):
    urls = [u.strip() for u in str(src or "").split(" ; ") if u.strip()]
    return " ".join(f'<a href="{esc(u)}" rel="noopener" target="_blank">{"spec" if i == 0 else i + 1}</a>' for i, u in enumerate(urls))


def chk(x):
    return " <small>(check)</small>" if x.get("status") == "verify" else ""


def num(v):
    return ("%g" % v) if isinstance(v, (int, float)) else ""


def write_table(d):
    """Refresh the built-in hardware tables on the Nyquist page (between lib:start / lib:end)."""
    page = HERE.parent.parent / "tools" / "nyquist" / "index.html"
    if not page.exists():
        return
    h = ['<div class="ny-lib">', '<h2>Built-in hardware</h2>',
         f'<p>{len(d["objectives"])} objectives, {len(d["cameras"])} cameras and {len(d["scanSystems"])} confocal and spinning-disk systems, '
         'each linked to the page its numbers were read from. Data: <a href="https://creativecommons.org/licenses/by/4.0/" rel="noopener license" target="_blank">CC BY 4.0</a>, '
         'compiled ' + esc(d["_meta"]["compiled"]) + '. Not sponsored by any maker.</p>',
         '<h3>Objectives</h3><div class="lm-tab-wrap"><table class="lm-tab"><thead><tr><th scope="col">Objective</th><th scope="col">Mag. / NA</th>'
         '<th scope="col">Immersion</th><th scope="col">WD mm</th><th scope="col">Tube lens</th><th scope="col">Source</th></tr></thead><tbody>']
    for o in d["objectives"]:
        h.append(f'<tr><th scope="row">{esc(o["brand"])} {esc(o["name"])}{chk(o)}</th><td>{num(o["mag"])}× / {o["na"]:.2f}</td><td>{esc(o["immersion"])}</td>'
                 f'<td>{num(o.get("wd_mm"))}</td><td>{o["tubeLens_mm"]} mm</td><td>{links(o["source"])}</td></tr>')
    h.append('</tbody></table></div><h3>Cameras</h3><div class="lm-tab-wrap"><table class="lm-tab"><thead><tr><th scope="col">Camera</th><th scope="col">Sensor</th>'
             '<th scope="col">Pixel µm</th><th scope="col">Pixels</th><th scope="col">Source</th></tr></thead><tbody>')
    for c in d["cameras"]:
        h.append(f'<tr><th scope="row">{esc(c["brand"])} {esc(c["name"])}{chk(c)}</th><td>{esc(c["sensor"])}</td><td>{num(c["pixel_um"])}</td>'
                 f'<td>{c["px"][0]} × {c["px"][1]}</td><td>{links(c["source"])}</td></tr>')
    h.append('</tbody></table></div><h3>Confocal and spinning disk</h3><div class="lm-tab-wrap"><table class="lm-tab"><thead><tr><th scope="col">System</th>'
             '<th scope="col">Type</th><th scope="col">Field / pinhole</th><th scope="col">Max frame</th><th scope="col">Source</th></tr></thead><tbody>')
    for s in d["scanSystems"]:
        if s["type"] == "point":
            what, fld = "point scan", esc(s.get("fieldWording") or f'{s["field_mm"]} mm')
        else:
            what, fld = "spinning disk", f'{s["pinhole_um"]} µm pinholes' + (f', {s["pitch_um"]} µm apart' if s.get("pitch_um") else "")
        frame = f'{s["maxFrame"]} px' if s.get("maxFrame") else ""
        disc = " <small>(discontinued)</small>" if s.get("discontinued") else ""
        h.append(f'<tr><th scope="row">{esc(s["brand"])} {esc(s["name"])}{disc}{chk(s)}</th><td>{what}</td><td>{fld}</td><td>{frame}</td><td>{links(s["source"])}</td></tr>')
    h.append('</tbody></table></div><p class="lm-note">(check) = at least one number derived or commonly cited, still to confirm against the maker. '
             'Dye peaks are shared with the Panel Designer list.</p></div>')
    html = page.read_text(encoding="utf-8")
    a, b = html.index("<!-- lib:start -->"), html.index("<!-- lib:end -->")
    html = html[:a] + "<!-- lib:start -->\n" + "\n".join(h) + "\n" + html[b:]
    page.write_text(html, encoding="utf-8")
    print("Updated the hardware tables in tools/nyquist/index.html")


if __name__ == "__main__":
    main()
